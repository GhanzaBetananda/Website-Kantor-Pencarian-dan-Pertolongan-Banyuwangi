export const getBeritaById = (id) => daftarBerita.find((b) => b.id === id);

export const getBeritaTerkait = (id, limit = 3) => {
  const current = getBeritaById(id);
  if (!current) return daftarBerita.slice(0, limit);
  return daftarBerita
    .filter((b) => b.id !== id && b.kategori === current.kategori)
    .concat(daftarBerita.filter((b) => b.id !== id && b.kategori !== current.kategori))
    .slice(0, limit);
};
